import { expect, it, vi } from "vitest";

it("프레임 호버는 부모 상태를 바꾸지 않고 Tab은 선택한 요소가 있을 때만 처리한다", async () => {
  vi.stubGlobal("ResizeObserver", class { observe() {} disconnect() {} });
  vi.stubGlobal("MutationObserver", class { observe() {} disconnect() {} });
  Object.defineProperty(Element.prototype, "scrollIntoView", { configurable: true, value: vi.fn() });
  if (!globalThis.CSS) vi.stubGlobal("CSS", {});
  document.body.innerHTML = '<button data-ks-n="1">대상</button><p data-ks-n="2">다음</p>';
  const send = vi.spyOn(window.parent, "postMessage").mockImplementation(() => {});
  await import("../blocks/html-bridge/main");
  send.mockClear();
  window.dispatchEvent(new MessageEvent("message", { source: window.parent, data: { type: "ks-html-mode", mode: "select" } }));
  document.querySelector("button")!.dispatchEvent(new MouseEvent("pointermove", { bubbles: true }));
  document.querySelector("p")!.dispatchEvent(new MouseEvent("pointermove", { bubbles: true }));
  await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()));
  expect(send).not.toHaveBeenCalled();
  const freeTab = new KeyboardEvent("keydown", { key: "Tab", bubbles: true, cancelable: true });
  document.querySelector("button")!.dispatchEvent(freeTab);
  expect(freeTab.defaultPrevented).toBe(false);
  expect(send).not.toHaveBeenCalled();
  window.dispatchEvent(new MessageEvent("message", { source: window.parent, data: { type: "ks-html-select-number", n: 1 } }));
  send.mockClear();
  const selectedTab = new KeyboardEvent("keydown", { key: "Tab", bubbles: true, cancelable: true });
  document.querySelector("button")!.dispatchEvent(selectedTab);
  expect(selectedTab.defaultPrevented).toBe(true);
  expect(send).toHaveBeenCalledWith(expect.objectContaining({ type: "ks-html-key", key: "Tab" }), "*");
  window.dispatchEvent(new MessageEvent("message", { source: window.parent, data: { type: "ks-html-select-number", n: null } }));
  window.dispatchEvent(new MessageEvent("message", { source: window.parent, data: { type: "ks-html-theme", tokens: { "--ks-color-accent": "#abcdef" } } }));
  expect(document.documentElement.style.getPropertyValue("--ks-color-accent")).toBe("#abcdef");
  await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()));
  const paragraph = document.querySelector("p")!;
  paragraph.innerHTML = '다음 <b>굵은</b> 문장';
  const range = document.createRange(); range.selectNodeContents(paragraph.firstChild!);
  getSelection()!.addRange(range);
  send.mockClear();
  paragraph.dispatchEvent(new MouseEvent("mouseup", { bubbles: true, detail: 2 }));
  expect(send).toHaveBeenCalledWith(expect.objectContaining({ type: "ks-html-select", selection: expect.objectContaining({ anchor: expect.objectContaining({ kind: "text" }) }) }), "*");
  expect(document.documentElement.hasAttribute("data-ks-pending")).toBe(true);
  document.querySelector("button")!.dispatchEvent(new MouseEvent("mousedown", { bubbles: true }));
  expect(document.documentElement.hasAttribute("data-ks-pending")).toBe(false);
  send.mockClear();
  window.dispatchEvent(new MessageEvent("message", { source: window.parent, data: { type: "ks-html-lock", locked: true } }));
  document.querySelector("button")!.dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true }));
  document.querySelector("button")!.dispatchEvent(new KeyboardEvent("keydown", { key: "Delete", bubbles: true, cancelable: true }));
  await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()));
  expect(send).not.toHaveBeenCalled();
  send.mockRestore();
  vi.unstubAllGlobals();
});
